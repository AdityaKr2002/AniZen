fun Anime.toSAnime(): eu.kanade.tachiyomi.source.model.SAnime = eu.kanade.tachiyomi.source.model.SAnime.create().also {
    it.url = url
    it.title = title
    it.artist = artist
    it.author = author
    it.description = description
    it.genre = genre?.joinToString(", ")
    it.status = status.toInt()
    it.thumbnail_url = thumbnailUrl
    it.initialized = initialized
}

fun eu.kanade.tachiyomi.source.model.SAnime.toDomainAnime(sourceId: Long): Anime {
    return Anime.create().copy(
        url = url,
        ogTitle = title,
        ogArtist = artist,
        ogAuthor = author,
        ogDescription = description,
        ogGenre = genre?.split(", ")?.map { it.trim() }?.filter { it.isNotBlank() },
